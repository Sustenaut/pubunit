#!/usr/bin/env python3
"""Write src/ucum_table.rs from the ucum-essence.xml that ucum-units bundles.

pubunit takes UCUM's atoms, prefixes and their values from the same file the
pinned ucum-units parses, so the two never disagree about what UCUM says.
ucum-units turns each value into a float; this keeps it as the decimal string
UCUM writes, so pubunit can read it as an exact rational.

    tools/gen-ucum-table.py           # rewrite src/ucum_table.rs
    tools/gen-ucum-table.py --check   # fail if the committed copy differs

The essence file is found through `cargo metadata`, at the ucum-units version
Cargo.lock pins. Only the standard library is used, and rustfmt.
"""

import json
import pathlib
import subprocess
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ucum_table.rs"
NS = {"u": "http://unitsofmeasure.org/ucum-essence"}
DIMS = {"L": "m", "T": "s", "M": "g", "A": "rad", "C": "K", "Q": "C", "F": "cd"}


def essence() -> tuple[pathlib.Path, str]:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT
        )
    )
    for pkg in meta["packages"]:
        if pkg["name"] == "ucum-units":
            path = pathlib.Path(pkg["manifest_path"]).parent / "vendor" / "ucum-essence.xml"
            return path, pkg["version"]
    sys.exit("ucum-units is not in the dependency graph")


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def render() -> str:
    path, version = essence()
    root = ET.parse(path).getroot()
    out = [
        f"// @generated by tools/gen-ucum-table.py from the ucum-essence.xml bundled in",
        f"// ucum-units {version}. Do not edit: run `make ucum-table`.",
        "//",
        "// UCUM is copyright 1999-2024 Regenstrief Institute, Inc., and is used under",
        "// the UCUM Copyright Notice and License, Version 1.1 (see NOTICE).",
        "",
        "use crate::table::{Atom, Prefix, Special};",
        "",
        "/// The UCUM version the table was read from.",
        f"pub(crate) const UCUM_VERSION: &str = {lit(root.get('version'))};",
        "/// The revision date of that version's essence file.",
        f"pub(crate) const UCUM_REVISION_DATE: &str = {lit(root.get('revision-date'))};",
        "/// The ucum-units release whose essence file this is.",
        f"pub(crate) const UCUM_UNITS_VERSION: &str = {lit(version)};",
        "",
        "pub(crate) static PREFIXES: &[Prefix] = &[",
    ]
    for p in root.findall("u:prefix", NS):
        value = p.find("u:value", NS).get("value")
        out.append(f"    Prefix {{ code: {lit(p.get('Code'))}, value: {lit(value)} }},")
    # pubunit's UCUM_BASE_UNITS hard-codes the seven, in this order.
    bases = [b.get("Code") for b in root.findall("u:base-unit", NS)]
    assert bases == list(DIMS.values()), bases
    assert all(DIMS[b.get("dim")] == b.get("Code") for b in root.findall("u:base-unit", NS))
    out += ["];", "", "pub(crate) static ATOMS: &[Atom] = &["]
    for u in root.findall("u:unit", NS):
        v = u.find("u:value", NS)
        metric = u.get("isMetric") == "yes"
        arbitrary = u.get("isArbitrary") == "yes"
        if u.get("isSpecial") == "yes":
            f = v.find("u:function", NS)
            value, unit = f.get("value"), f.get("Unit")
            special = f"Some(Special({lit(f.get('name'))}))"
        else:
            value, unit = v.get("value"), v.get("Unit")
            special = "None"
        out.append(
            f"    Atom {{ code: {lit(u.get('Code'))}, metric: {str(metric).lower()}, "
            f"arbitrary: {str(arbitrary).lower()}, special: {special}, "
            f"value: {lit(value)}, unit: {lit(unit)} }},"
        )
    out += ["];", ""]
    # In rustfmt's layout, so `cargo fmt` leaves the generated file alone.
    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input="\n".join(out), capture_output=True, text=True, check=True, cwd=ROOT,
    ).stdout


def main() -> None:
    text = render()
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run `make ucum-table`")
        print("ucum-table: current")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

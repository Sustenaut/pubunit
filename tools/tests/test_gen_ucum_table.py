"""Tests for tools/gen-ucum-table.py.

The script is not crate code and the functional suite in tests/ never runs
it, so it is tested here, in-process, by loading it as a module. `make
script-tests` runs these under coverage for SonarQube Cloud.
"""

from __future__ import annotations

import datetime
import importlib.util
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent.parent


def load():
    path = ROOT / "tools" / "gen-ucum-table.py"
    spec = importlib.util.spec_from_file_location("gen_ucum_table", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load()
TODAY = datetime.date.today().isoformat()


@pytest.fixture(scope="module")
def committed() -> str:
    return (ROOT / "src" / "ucum_table.generated.rs").read_text()


@pytest.fixture
def out(monkeypatch, committed):
    """A copy of the committed table that the script reads and writes.

    It sits in target/, inside the repository, so the script still runs
    cargo and rustfmt from the repository root.
    """
    path = ROOT / "target" / "script-tests" / "ucum_table.generated.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(committed)
    monkeypatch.setattr(gen, "OUT", path)
    yield path
    path.unlink(missing_ok=True)


def run(monkeypatch, *argv):
    monkeypatch.setattr(sys, "argv", ["gen-ucum-table.py", *argv])
    gen.main()


def restamp(text: str, date: str) -> str:
    return gen.STAMP.sub(f"// @generated by tools/gen-ucum-table.py on {date}.", text)


def test_the_header_names_generator_source_and_date():
    head = gen.render("2000-01-02").splitlines()[:4]
    assert head[0] == "// @generated by tools/gen-ucum-table.py on 2000-01-02."
    assert head[1].startswith("// Source: vendor/ucum-essence.xml in the ucum-units ")
    assert "make ucum-table" in head[3]


def test_the_committed_table_is_current(out, monkeypatch, capsys):
    run(monkeypatch, "--check")
    assert "ucum-table: current" in capsys.readouterr().out


def test_check_ignores_only_the_date(out, monkeypatch, committed, capsys):
    out.write_text(restamp(committed, "2000-01-02"))
    run(monkeypatch, "--check")
    assert "current" in capsys.readouterr().out


def test_check_fails_on_a_stale_table(out, monkeypatch, committed):
    out.write_text(committed.replace('code: "lm"', 'code: "xx"'))
    with pytest.raises(SystemExit) as stop:
        run(monkeypatch, "--check")
    assert "is stale: run `make ucum-table`" in str(stop.value)


def test_an_unchanged_table_keeps_its_date(out, monkeypatch, committed, capsys):
    old = restamp(committed, "2000-01-02")
    out.write_text(old)
    run(monkeypatch)
    assert out.read_text() == old
    assert "current" in capsys.readouterr().out


def test_a_changed_table_takes_todays_date(out, monkeypatch, committed, capsys):
    out.write_text(restamp(committed, "2000-01-02").replace('code: "lm"', 'code: "xx"'))
    run(monkeypatch)
    assert out.read_text() == restamp(committed, TODAY)
    assert "wrote target/script-tests/ucum_table.generated.rs" in capsys.readouterr().out


def test_a_missing_table_is_written_with_todays_date(out, monkeypatch, committed):
    out.unlink()
    run(monkeypatch)
    assert out.read_text() == restamp(committed, TODAY)

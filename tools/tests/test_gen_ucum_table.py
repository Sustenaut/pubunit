"""Steps for ucum-table.feature: tools/gen-ucum-table.py, loaded as a
module and run in-process."""

from __future__ import annotations

import datetime
import importlib.util
import sys
from pathlib import Path

import pytest
from pytest_bdd import given, parsers, scenarios, then, when

scenarios("ucum-table.feature")

ROOT = Path(__file__).resolve().parent.parent.parent


def load():
    path = ROOT / "tools" / "gen-ucum-table.py"
    spec = importlib.util.spec_from_file_location("gen_ucum_table", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load()
TODAY = datetime.date.today().isoformat()


@pytest.fixture(scope="module")
def committed() -> str:
    return (ROOT / "src" / "ucum_table.generated.rs").read_text()


@pytest.fixture
def out(monkeypatch, committed):
    """A copy of the committed table that the script reads and writes.

    It sits in target/, inside the repository, so the script still runs
    cargo and rustfmt from the repository root.
    """
    path = ROOT / "target" / "script-tests" / "ucum_table.generated.rs"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(committed)
    monkeypatch.setattr(gen, "OUT", path)
    yield path
    path.unlink(missing_ok=True)


def run(monkeypatch, *argv):
    monkeypatch.setattr(sys, "argv", ["gen-ucum-table.py", *argv])
    gen.main()


def restamp(text: str, date: str) -> str:
    return gen.STAMP.sub(f"// @generated by tools/gen-ucum-table.py on {date}.", text)


@when(parsers.parse('the table is rendered on "{date}"'), target_fixture="head")
def rendered(date):
    return gen.render(date).splitlines()[:4]


@then(parsers.parse('its first line is "{line}"'))
def first_line(head, line):
    assert head[0] == line


@then("its second line names vendor/ucum-essence.xml in the ucum-units repository")
def second_line(head):
    assert head[1].startswith("// Source: vendor/ucum-essence.xml in the ucum-units ")


@then("its fourth line says to run make ucum-table")
def fourth_line(head):
    assert "make ucum-table" in head[3]


@given("a copy of the committed table")
def copy(out):
    return out


@given(parsers.parse('a copy of the committed table stamped "{date}"'))
def copy_stamped(out, committed, date):
    out.write_text(restamp(committed, date))


@given(parsers.parse('a copy of the committed table with "{old}" changed to "{new}"'))
def copy_changed(out, committed, old, new):
    out.write_text(committed.replace(f'code: "{old}"', f'code: "{new}"'))


@given(parsers.parse('a copy of the committed table stamped "{date}" with "{old}" changed to "{new}"'))
def copy_stamped_changed(out, committed, date, old, new):
    out.write_text(restamp(committed, date).replace(f'code: "{old}"', f'code: "{new}"'))


@given("the copy is removed")
def removed(out):
    out.unlink()


@when(parsers.parse('the script runs with "{flag}"'), target_fixture="ran")
def runs_with(out, monkeypatch, capsys, flag):
    return run_catching(monkeypatch, capsys, flag)


@when("the script runs", target_fixture="ran")
def runs(out, monkeypatch, capsys):
    return run_catching(monkeypatch, capsys)


def run_catching(monkeypatch, capsys, *argv):
    """(the SystemExit it stopped with, or None; what it printed)."""
    try:
        run(monkeypatch, *argv)
    except SystemExit as stop:
        return stop, capsys.readouterr().out
    return None, capsys.readouterr().out


@then(parsers.parse('it prints "{text}"'))
def prints(ran, text):
    stopped, printed = ran
    assert stopped is None, stopped
    assert text in printed


@then(parsers.parse('it stops, saying "{text}"'))
def stops(ran, text):
    stopped, _ = ran
    assert stopped is not None and text in str(stopped.code)


@then(parsers.parse('the table is still stamped "{date}"'))
def still_stamped(out, committed, date):
    assert out.read_text() == restamp(committed, date)


@then("the table is the committed one stamped today")
def stamped_today(out, committed):
    assert out.read_text() == restamp(committed, TODAY)
